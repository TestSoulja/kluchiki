export const LOSS_CLOSING =
  'Копия файла — единственное, что защищает от всего списка. Кнопка ' +
  '«Экспорт и импорт»; дата копии видна на списке. Файл зашифрован: без ' +
  'мастер-пароля его не открыть.';

export function renderLoss(app) {
  if (!app.session) {
    app.reset('unlock');
    return;
  }
  const page = el('div', { class: 'page page-narrow' });

  const back = iconButton('Назад к записям', '', () => app.back());
  back.replaceChildren(backIcon());
  page.append(
    el(
      'div',
      { class: 'screen-header' },
      back,
      heading(LOSS_TITLE),
      el('span', { class: 'header-spacer' }),
    ),
  );

  const list = el('ul', { class: 'loss-list' });
  for (const item of LOSS_ITEMS) {
    list.append(
      el(
        'li',
        {},
        el('strong', { text: `${item.title}.` }),
        ` ${item.text}`,
      ),
    );
  }
  page.append(
    list,
    el('p', { class: 'text', text: LOSS_CLOSING }),
  );

  app.root.replaceChildren(page);
  focusHeading(page);
}
